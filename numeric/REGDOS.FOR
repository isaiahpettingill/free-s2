      PROGRAM S2REG
      INTEGER N,P,I,IOS,STATUS
      DOUBLE PRECISION X(2048),Y(1024),B(32),RES(1024),TOL
      READ(5,*,IOSTAT=IOS) N,P,TOL
      IF (IOS.NE.0) STOP 1
      IF (N.LT.1.OR.N.GT.1024.OR.P.LT.1.OR.P.GT.32) STOP 2
      IF (N*P.GT.2048) STOP 2
      DO 10 I=1,N*P
        READ(5,*,IOSTAT=IOS) X(I)
        IF (IOS.NE.0) STOP 3
   10 CONTINUE
      DO 20 I=1,N
        READ(5,*,IOSTAT=IOS) Y(I)
        IF (IOS.NE.0) STOP 3
   20 CONTINUE
      CALL S2QR(X,Y,N,P,TOL,B,RES,STATUS)
      WRITE(6,*) STATUS
      IF (STATUS.NE.0) STOP
      DO 30 I=1,P
        WRITE(6,100) B(I)
   30 CONTINUE
      DO 40 I=1,N
        WRITE(6,100) RES(I)
   40 CONTINUE
  100 FORMAT(1X,E25.16E3)
      END
