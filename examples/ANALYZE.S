# Run from the directory containing DATA.TXT.
d <- scan("DATA.TXT",what=list(x=0,y=0,region=""))
print(mean(d$y))
print(var(d$y))
print(tapply(d$y,list(category(d$region)),mean))
fit <- lsfit(d$x,d$y)
print(as.vector(fit$coef))
print(round(fit$residuals,8))
svg("FIT.SVG")
plot(d$x,d$y,main="Measured response",xlab="Input",ylab="Response")
abline(fit,col="red")
dev.off()
postscript("FIT.PS")
plot(d$x,d$y,main="Measured response")
abline(fit)
dev.off()
write(fit$residuals,"RESID.TXT",ncolumns=1)
dump(c("d","fit"),"WORK.S")
